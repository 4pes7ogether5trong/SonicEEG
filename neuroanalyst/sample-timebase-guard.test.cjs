'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {validate,compare,sampleAt,compareReviewedWindows}=require('./sample-timebase-guard.cjs');
const t=()=>({recordingId:'synthetic',sampleRateHz:256,firstSampleIndex:0,sampleCount:307200,clockOriginSeconds:0});
test('valid reference 20-minute clock',()=>assert.deepEqual(validate(t()),[]));
test('invalid sample rate',()=>assert.ok(validate({...t(),sampleRateHz:0}).length));
test('sample index overflow',()=>assert.ok(validate({...t(),firstSampleIndex:Number.MAX_SAFE_INTEGER}).length));
test('matching clock',()=>assert.equal(compare(t(),t()).comparable,true));
test('sampling mismatch',()=>assert.ok(compare(t(),{...t(),sampleRateHz:128}).reasons.includes('sampleRateHz_mismatch')));
test('clock origin mismatch',()=>assert.ok(compare(t(),{...t(),clockOriginSeconds:1}).reasons.includes('clockOriginSeconds_mismatch')));
test('sample count mismatch',()=>assert.ok(compare(t(),{...t(),sampleCount:10}).reasons.includes('sampleCount_mismatch')));
test('first sample mismatch',()=>assert.ok(compare(t(),{...t(),firstSampleIndex:1}).reasons.includes('firstSampleIndex_mismatch')));
test('seconds to sample',()=>assert.equal(sampleAt(t(),10),2560));
test('last sample valid',()=>assert.equal(sampleAt(t(),1200-1/256),307199));
test('end exclusive',()=>assert.throws(()=>sampleAt(t(),1200),/outside_sample_window/));
test('full window accepted',()=>assert.equal(compareReviewedWindows(t(),t(),[[0,1200]]).comparable,true));
test('out of bounds window rejected',()=>assert.equal(compareReviewedWindows(t(),t(),[[0,1201]]).comparable,false));
test('invalid window rejected',()=>assert.equal(compareReviewedWindows(t(),t(),[[5,4]]).comparable,false));
