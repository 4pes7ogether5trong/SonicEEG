// Reproducible static Worker package. Requires Node and Python 3 (stdlib only).
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const root=path.dirname(fileURLToPath(import.meta.url));
execFileSync('python3',['-c',String.raw`
from pathlib import Path
import sys, zipfile
root=Path(sys.argv[1])
with zipfile.ZipFile(root/'converter.zip','w',compression=zipfile.ZIP_DEFLATED) as z:
    for name in ['convert_local.py','requirements.txt','QUICKSTART.md','FORMAT.md']:
        info=zipfile.ZipInfo('eeg-review-converter/'+name,date_time=(2026,1,1,0,0,0))
        info.compress_type=zipfile.ZIP_DEFLATED
        z.writestr(info,(root/'converter'/name).read_bytes())
`,root]);
const types={'index.html':'text/html; charset=utf-8','core.js':'application/javascript; charset=utf-8','formats.js':'application/javascript; charset=utf-8','app.js':'application/javascript; charset=utf-8','style.css':'text/css; charset=utf-8','icon.svg':'image/svg+xml','manifest.webmanifest':'application/manifest+json'};
const assets={};for(const [name,type] of Object.entries(types))assets[name==='index.html'?'/':'/'+name]=[type,fs.readFileSync(path.join(root,name),'utf8')];
assets['/converter.zip']=['application/zip',fs.readFileSync(path.join(root,'converter.zip')).toString('base64'),'base64'];
const handler=`export default {fetch(request){
 const url=new URL(request.url);
 const headers={"X-Content-Type-Options":"nosniff","Referrer-Policy":"no-referrer","Permissions-Policy":"camera=(), microphone=(), geolocation=()","Content-Security-Policy":"default-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; manifest-src 'self'; connect-src 'none'; font-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'","Cache-Control":"no-cache"};
 if(!["GET","HEAD"].includes(request.method))return new Response("Method not allowed",{status:405,headers:{...headers,Allow:"GET, HEAD"}});
 const item=assets[url.pathname];if(!item)return new Response("Not found",{status:404,headers});
 const body=request.method==="HEAD"?null:item[2]==="base64"?Uint8Array.from(atob(item[1]),c=>c.charCodeAt(0)):item[1];
 return new Response(body,{headers:{...headers,"Content-Type":item[0],...(item[2]==="base64"?{"Content-Disposition":"attachment; filename=EEG-Review-Local-Converter.zip"}:{})}});
}};`;
fs.writeFileSync(path.join(root,'worker.mjs'),'// Generated by build-worker.mjs. Static shell only; no patient storage or request-body reads.\nconst assets='+JSON.stringify(assets)+';\n'+handler+'\n');
console.log('Built worker.mjs and converter.zip ('+fs.statSync(path.join(root,'converter.zip')).size+' bytes).');
